'use strict';
const assert = require('node:assert/strict');
const { test } = require('node:test');
const { createHash } = require('node:crypto');
const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');

test('native Cargo.lock checkout bytes match independently audited source on all OSes', () => {
  const lock = readFileSync(resolve(__dirname, '../../native/capability-probe/Cargo.lock'));
  // Reviewed T011 atomic publication experiment: add pinned cap-tempfile 4.0.3
  // and its Cargo-resolved transitive lock graph. This keeps byte-exact custody;
  // changing any locked crate requires a fresh independent review.
  assert.equal(lock.byteLength, 21435, 'Unexpected Rust dependency lock size');
  assert.equal(lock.includes(13), false, 'Cargo.lock checkout contains CR bytes; enforce LF');
  assert.equal(createHash('sha256').update(lock).digest('hex'),
    '7b329eb268e923abb1cc48554cfcf8edb4504f91aa65d2645023a9619bbfc80e', 'Cargo.lock bytes changed from audited source');
  assert.match(lock.toString('utf8'), /^# This file is automatically @generated by Cargo\./);
});
